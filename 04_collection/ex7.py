# 집합 기초

# ===========================================================
#  집합 (set): 여러 객체를 순서 없이 중복을 허용하지 않고 저장하는 변경 가능한 자료형
#  집합의 특징
#  1. ( mutable, 변경가능 )
#  2. ( iterable, 반복가능 )
#  3. ( sequence x, 인덱싱과 슬라이싱 불가 )= (dict)
#  4. ( 중복 허용 안함 )
# ===========================================================

# 집합 생성
a = set()
b = {}  # 딕셔너리
print(type(a))

a = {3, 3, 3, 2, 2, 1}
print(a)  # 8로 나눈 값의 나머지를 순서로 정렬
b = {100, 8, 30}
print(b)

# ===========================================================
# 1. 집합은 mutable하다. (변경 가능) = (list, dict)
# ===========================================================
a.update({3, 4})
print(a)

a.remove(3)
print(a)

print(a.pop())
print(a)
# ===========================================================
# 2. 집합은 iterable하다. (반복 가능) = ()
# ===========================================================

# 집합 순회
for i in a:
    print(i)


# ===========================================================
# 3. 집합은 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================
# a[0] = 10
# tuple.    list.
# ===========================================================
# 4. 집합은 중복을 허용하지 않는다.
# ===========================================================
s = {10, 10, 20, 20, 20}
print(s)
# ===========================================================
#  파이썬 내장 함수
# ===========================================================
print(len(s))
print(sum(s))
print(min(s))
print(max(s))
print(sorted(s))

# 집합 합치기
s2 = {30, 40}
print(s.union(s2))
s.update(s2)
print(s)

